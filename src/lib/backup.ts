import { shellQuote } from "./logRotation.js";
import { sshExec } from "./ssh.js";
import type { BackupConfig, SSHTarget } from "../types.js";

// Backups of an app's data, run *on the server* by a self-contained POSIX
// script that nodeploy installs at ~/.nodeploy/backup-<service>.sh. One
// script serves every trigger: the cron schedule, `nodeploy backup now`, the
// snapshot before each deploy, and the one before a restore. It needs no
// nodeploy and no Node on the server — just sh, tar, gzip, and (for
// consistent SQLite snapshots) sqlite3.

export const DEFAULT_BACKUP_SCHEDULE = "daily";
export const DEFAULT_BACKUP_KEEP = 14;

export type BackupReason = "scheduled" | "manual" | "pre-deploy" | "pre-restore";

/** Where an app's backups live: outside its checkout, so `git reset`,
 * `git clean`, and `nodeploy remove --purge` never touch them. */
export function backupDir(service: string): string {
  return `$HOME/.nodeploy/backups/${service}`;
}

export function backupScriptPath(service: string): string {
  return `$HOME/.nodeploy/backup-${service}.sh`;
}

/** The cron line's trailing marker, so setup can find and replace it. */
export function cronMarker(service: string): string {
  return `# nodeploy:backup:${service}`;
}

const CRON_FIELD = /^[\d*/,-]+$/;

/** "daily" | "hourly" | "off" | a 5-field cron expression. */
export function isValidSchedule(schedule: string): boolean {
  if (["daily", "hourly", "off"].includes(schedule)) return true;
  const fields = schedule.trim().split(/\s+/);
  return fields.length === 5 && fields.every((f) => CRON_FIELD.test(f));
}

/** Spreads apps' scheduled backups over the hour instead of all at :00. */
function minuteFor(service: string): number {
  let hash = 0;
  for (const ch of service) hash = (hash * 31 + ch.charCodeAt(0)) % 60;
  return hash;
}

/** Cron timing for a schedule, or null for "off". Daily runs at 02:MM,
 * server time — outside office hours. */
export function cronTiming(schedule: string, service: string): string | null {
  if (schedule === "off") return null;
  const minute = minuteFor(service);
  if (schedule === "daily") return `${minute} 2 * * *`;
  if (schedule === "hourly") return `${minute} * * * *`;
  return schedule.trim().split(/\s+/).join(" ");
}

export function cronLine(service: string, schedule: string): string | null {
  const timing = cronTiming(schedule, service);
  if (!timing) return null;
  return `${timing} /bin/sh "${backupScriptPath(service)}" scheduled >> "${backupDir(service)}/backup.log" 2>&1 ${cronMarker(service)}`;
}

/** The backup script. Prints tab-separated lines: `BACKUP <archive>
 * <bytes>`, `MISSING <path>`, `WARN <message>`, `PRUNED <archive>`, and on
 * failure `ERROR <message>` with a non-zero exit. */
export function buildBackupScript(opts: {
  service: string;
  deployPath: string;
  paths: string[];
  keep: number;
  nodeployVersion: string;
}): string {
  const { service, deployPath, paths, keep, nodeployVersion } = opts;
  return `#!/bin/sh
# Managed by nodeploy ${nodeployVersion}: backups of ${service}'s data.
# Regenerated by \`nodeploy backup setup\` (also run by setup and deploy) —
# edit the \`backup\` block in nodeploy.yml instead of this file.
set -u
APP_DIR="${deployPath}"
DEST="${backupDir(service)}"
KEEP=${keep}
REASON=\${1:-manual}
umask 077

if command -v sha256sum >/dev/null 2>&1; then SHA="sha256sum"; else SHA="shasum -a 256"; fi
mkdir -p "$DEST" || { printf 'ERROR\\tcannot create %s\\n' "$DEST"; exit 2; }

# One run at a time (cron and a manual run could overlap); a lock left by a
# run that died is taken over.
LOCK="$DEST/.lock"
if ! mkdir "$LOCK" 2>/dev/null; then
  if kill -0 "$(cat "$LOCK/pid" 2>/dev/null)" 2>/dev/null; then
    printf 'ERROR\\tanother backup of ${service} is running\\n'; exit 3
  fi
  rm -rf "$LOCK"; mkdir "$LOCK" || exit 3
fi
echo $$ > "$LOCK/pid"
STAGE=$(mktemp -d) || exit 2
trap 'rm -rf "$STAGE" "$LOCK"' EXIT INT TERM

cd "$APP_DIR" 2>/dev/null || { printf 'ERROR\\tapp directory %s not found\\n' "$APP_DIR"; exit 2; }
mkdir -p "$STAGE/files"
# A file, not a variable: failures inside \`find | while\` happen in a subshell.
fail() { printf 'ERROR\\t%s\\n' "$1"; touch "$STAGE/.failed"; }

is_sqlite() { [ -f "$1" ] && [ "$(head -c 15 -- "$1" 2>/dev/null)" = "SQLite format 3" ]; }

# A SQLite database being written can't be copied byte by byte safely:
# sqlite3's online backup takes a consistent snapshot (WAL included).
snap_sqlite() {
  if command -v sqlite3 >/dev/null 2>&1; then
    rm -f -- "$2" "$2-wal" "$2-shm" "$2-journal"
    sqlite3 "$1" ".backup '$2'" || { fail "sqlite backup of $1 failed"; return; }
    # Make the snapshot one self-contained file: a copy left in WAL mode can
    # keep data in its own -wal file, which restore would drop as stale.
    sqlite3 "$2" "pragma journal_mode=delete;" >/dev/null || fail "could not finalize the snapshot of $1"
    rm -f -- "$2-wal" "$2-shm"
  else
    printf 'WARN\\t%s is a SQLite database but sqlite3 is not installed: copied as-is, which can be inconsistent if it was being written (apt install sqlite3)\\n' "$1"
  fi
}

snap() {
  if [ ! -e "$1" ]; then printf 'MISSING\\t%s\\n' "$1"; return; fi
  mkdir -p "$STAGE/files/$(dirname -- "$1")"
  if [ -d "$1" ]; then
    cp -pR -- "$1" "$STAGE/files/$1" || { fail "could not copy $1"; return; }
    find "$1" -type f | while IFS= read -r f; do
      if is_sqlite "$f"; then snap_sqlite "$f" "$STAGE/files/$f"; fi
    done
  elif is_sqlite "$1"; then
    cp -p -- "$1" "$STAGE/files/$1" && snap_sqlite "$1" "$STAGE/files/$1"
  else
    cp -p -- "$1" "$STAGE/files/$1" || fail "could not copy $1"
  fi
}

${paths.map((p) => `snap ${shellQuote(p)}`).join("\n")}
[ ! -e "$STAGE/.failed" ] || exit 4

TS=$(date +%Y-%m-%d_%H-%M-%S)
NAME="\${TS}_\${REASON}"
{
  echo "service=${service}"
  echo "created=$(date '+%Y-%m-%d %H:%M:%S %z')"
  echo "reason=$REASON"
  echo "commit=$(git rev-parse HEAD 2>/dev/null || echo none)"
  echo "nodeploy=${nodeployVersion}"
${paths.map((p) => `  echo "path="${shellQuote(p)}`).join("\n")}
} > "$STAGE/MANIFEST"
(cd "$STAGE/files" && find . -type f -exec $SHA {} +) > "$STAGE/SHA256SUMS"

# Written under a temporary name and renamed, so a half-written archive is
# never listed as a backup.
tar -czf "$DEST/$NAME.tar.gz.part" -C "$STAGE" MANIFEST SHA256SUMS files \\
  && gzip -t "$DEST/$NAME.tar.gz.part" \\
  && mv "$DEST/$NAME.tar.gz.part" "$DEST/$NAME.tar.gz" \\
  || { rm -f "$DEST/$NAME.tar.gz.part"; printf 'ERROR\\tcould not write the archive (disk full?)\\n'; exit 5; }
printf 'BACKUP\\t%s\\t%s\\n' "$DEST/$NAME.tar.gz" "$(wc -c < "$DEST/$NAME.tar.gz" | tr -d ' ')"

ls -1 "$DEST" | grep -E '^[0-9]{4}-[0-9]{2}-[0-9]{2}_[0-9]{2}-[0-9]{2}-[0-9]{2}_.*\\.tar\\.gz$' | sort -r | sed "1,\${KEEP}d" | while IFS= read -r old; do
  rm -f -- "$DEST/$old" && printf 'PRUNED\\t%s\\n' "$old"
done
`;
}

export interface BackupRunResult {
  archive: string | null;
  bytes: number;
  missing: string[];
  warnings: string[];
  pruned: string[];
  error: string | null;
}

export function parseBackupOutput(stdout: string): BackupRunResult {
  const result: BackupRunResult = {
    archive: null,
    bytes: 0,
    missing: [],
    warnings: [],
    pruned: [],
    error: null,
  };
  for (const line of stdout.split("\n")) {
    const [tag, a = "", b = ""] = line.split("\t");
    if (tag === "BACKUP") {
      result.archive = a;
      result.bytes = Number(b) || 0;
    } else if (tag === "MISSING") result.missing.push(a);
    else if (tag === "WARN") result.warnings.push(a);
    else if (tag === "PRUNED") result.pruned.push(a);
    else if (tag === "ERROR") result.error = a;
  }
  return result;
}

/** Writes the script and points the SSH user's crontab at it (or removes
 * the entry for schedule "off"). Idempotent: other crontab lines are kept,
 * and this app's line is replaced, never duplicated. */
export function setupScript(opts: {
  service: string;
  script: string;
  schedule: string;
}): string {
  const line = cronLine(opts.service, opts.schedule);
  const marker = cronMarker(opts.service);
  return `set -eu
mkdir -p "$HOME/.nodeploy" "${backupDir(opts.service)}"
chmod 700 "$HOME/.nodeploy"
cat > "${backupScriptPath(opts.service)}.tmp" <<'NODEPLOY_BACKUP_SCRIPT'
${opts.script}NODEPLOY_BACKUP_SCRIPT
chmod 700 "${backupScriptPath(opts.service)}.tmp"
mv "${backupScriptPath(opts.service)}.tmp" "${backupScriptPath(opts.service)}"
if command -v crontab >/dev/null 2>&1; then
  current=$(crontab -l 2>/dev/null | grep -vF ${shellQuote(marker)} || true)
  { [ -n "$current" ] && printf '%s\\n' "$current"; ${line ? `printf '%s\\n' ${shellQuote(line)}` : "true"}; } | crontab -
  printf 'CRON\\t%s\\n' ${shellQuote(line ?? "off")}
  if command -v systemctl >/dev/null 2>&1 && ! systemctl is-active --quiet cron 2>/dev/null; then
    printf 'WARN\\tthe cron service is not running, so scheduled backups will not run (sudo systemctl enable --now cron)\\n'
  fi
else
  printf 'WARN\\tcrontab is not installed, so scheduled backups will not run (sudo apt install cron)\\n'
fi
`;
}

export async function setupBackups(
  target: SSHTarget,
  service: string,
  deployPath: string,
  backup: BackupConfig,
  nodeployVersion: string,
): Promise<{ cron: string | null; warnings: string[] }> {
  const script = buildBackupScript({
    service,
    deployPath,
    paths: backup.paths,
    keep: backup.keep,
    nodeployVersion,
  });
  const { stdout } = await sshExec(target, "sh -s", {
    input: setupScript({ service, script, schedule: backup.schedule }),
  });
  let cron: string | null = null;
  const warnings: string[] = [];
  for (const line of stdout.split("\n")) {
    const [tag, value = ""] = line.split("\t");
    if (tag === "CRON") cron = value === "off" ? null : value;
    if (tag === "WARN") warnings.push(value);
  }
  return { cron, warnings };
}

export async function runBackup(
  target: SSHTarget,
  service: string,
  reason: BackupReason,
): Promise<BackupRunResult> {
  try {
    const { stdout } = await sshExec(
      target,
      `/bin/sh "${backupScriptPath(service)}" ${reason}`,
    );
    return parseBackupOutput(stdout);
  } catch (error) {
    const stdout = (error as { stdout?: string }).stdout ?? "";
    const parsed = parseBackupOutput(stdout);
    if (!parsed.error) {
      parsed.error = /No such file|not found|can't open/.test(String((error as Error).message))
        ? "the backup script isn't on the server yet — run `nodeploy backup setup`"
        : (error as Error).message;
    }
    return parsed;
  }
}

export interface BackupEntry {
  name: string;
  path: string;
  created: string;
  reason: string;
  bytes: number;
}

const ARCHIVE_NAME = /^(\d{4}-\d{2}-\d{2})_(\d{2})-(\d{2})-(\d{2})_(.+)\.tar\.gz$/;

export function parseBackupListing(stdout: string, dir: string): {
  entries: BackupEntry[];
  cron: string | null;
} {
  const entries: BackupEntry[] = [];
  let cron: string | null = null;
  for (const line of stdout.split("\n")) {
    if (line.startsWith("CRON\t")) {
      cron = line.slice(5) || null;
      continue;
    }
    const m = /^\S+\s+\d+\s+\S+\s+\S+\s+(\d+)\s+\S+\s+\S+\s+\S+\s(.+)$/.exec(line);
    if (!m) continue;
    const name = m[2];
    const parts = ARCHIVE_NAME.exec(name);
    if (!parts) continue;
    entries.push({
      name,
      path: `${dir}/${name}`,
      created: `${parts[1]} ${parts[2]}:${parts[3]}:${parts[4]}`,
      reason: parts[5],
      bytes: Number(m[1]),
    });
  }
  entries.sort((a, b) => (a.name < b.name ? 1 : -1));
  return { entries, cron };
}

export async function listBackups(
  target: SSHTarget,
  service: string,
): Promise<{ entries: BackupEntry[]; cron: string | null; dir: string }> {
  const { stdout } = await sshExec(
    target,
    `D="${backupDir(service)}"; echo "DIR $D"; LC_ALL=C ls -ln -- "$D" 2>/dev/null; printf 'CRON\\t%s\\n' "$(crontab -l 2>/dev/null | grep -F ${shellQuote(cronMarker(service))} | head -1)"`,
  );
  const dirLine = stdout.split("\n").find((l) => l.startsWith("DIR "));
  const dir = dirLine ? dirLine.slice(4) : backupDir(service);
  return { ...parseBackupListing(stdout, dir), dir };
}

/** Restores an archive's files into the app's directory. Checks every
 * file's checksum before touching anything; replaces each path with a
 * rename, so no path is ever half-written; drops a restored SQLite
 * database's stale -wal/-shm files, which SQLite would otherwise replay
 * over the restored data. The app must be stopped first. Prints
 * `RESTORED <path>` / `SKIPPED <path>` / `ERROR <message>`. */
export function buildRestoreScript(deployPath: string, archive: string): string {
  return `set -u
APP_DIR="${deployPath}"
ARCHIVE=${archive.startsWith("$HOME") ? `"${archive}"` : shellQuote(archive)}
if command -v sha256sum >/dev/null 2>&1; then SHA="sha256sum"; else SHA="shasum -a 256"; fi
STAGE=$(mktemp -d) || exit 2
trap 'rm -rf "$STAGE"' EXIT INT TERM
[ -f "$ARCHIVE" ] || { printf 'ERROR\\tbackup %s not found\\n' "$ARCHIVE"; exit 2; }
tar -xzf "$ARCHIVE" -C "$STAGE" 2>/dev/null || { printf 'ERROR\\tthe archive is damaged and could not be read\\n'; exit 3; }
[ -f "$STAGE/MANIFEST" ] && [ -f "$STAGE/SHA256SUMS" ] || { printf 'ERROR\\tnot a nodeploy backup (no MANIFEST)\\n'; exit 3; }
(cd "$STAGE/files" && $SHA -c ../SHA256SUMS >/dev/null 2>&1) || { printf 'ERROR\\tchecksums do not match: the archive is damaged, nothing was restored\\n'; exit 3; }
cd "$APP_DIR" || { printf 'ERROR\\tapp directory %s not found\\n' "$APP_DIR"; exit 2; }
grep '^path=' "$STAGE/MANIFEST" | sed 's/^path=//' | while IFS= read -r p; do
  if [ ! -e "$STAGE/files/$p" ]; then printf 'SKIPPED\\t%s\\n' "$p"; continue; fi
  mkdir -p "$(dirname -- "$p")"
  rm -rf -- "$p.nodeploy-restore"
  cp -pR -- "$STAGE/files/$p" "$p.nodeploy-restore" || { printf 'ERROR\\tcould not stage %s\\n' "$p"; exit 4; }
  if [ -d "$p.nodeploy-restore" ] && [ -e "$p" ]; then
    mv -- "$p" "$p.nodeploy-old" && mv -- "$p.nodeploy-restore" "$p" && rm -rf -- "$p.nodeploy-old"
  else
    mv -f -- "$p.nodeploy-restore" "$p"
  fi || { printf 'ERROR\\tcould not put %s in place\\n' "$p"; exit 4; }
  find "$p" -type f 2>/dev/null | while IFS= read -r f; do
    if [ "$(head -c 15 -- "$f" 2>/dev/null)" = "SQLite format 3" ]; then rm -f -- "$f-wal" "$f-shm" "$f-journal"; fi
  done
  printf 'RESTORED\\t%s\\n' "$p"
done
`;
}

export interface RestoreResult {
  restored: string[];
  skipped: string[];
  error: string | null;
}

export function parseRestoreOutput(stdout: string): RestoreResult {
  const result: RestoreResult = { restored: [], skipped: [], error: null };
  for (const line of stdout.split("\n")) {
    const [tag, value = ""] = line.split("\t");
    if (tag === "RESTORED") result.restored.push(value);
    else if (tag === "SKIPPED") result.skipped.push(value);
    else if (tag === "ERROR") result.error = value;
  }
  return result;
}

export async function restoreArchive(
  target: SSHTarget,
  deployPath: string,
  archive: string,
): Promise<RestoreResult> {
  try {
    const { stdout } = await sshExec(target, "sh -s", {
      input: buildRestoreScript(deployPath, archive),
    });
    return parseRestoreOutput(stdout);
  } catch (error) {
    const parsed = parseRestoreOutput((error as { stdout?: string }).stdout ?? "");
    parsed.error ??= (error as Error).message;
    return parsed;
  }
}
